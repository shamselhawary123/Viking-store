create table if not exists public.product_variants (
  id bigint generated by default as identity primary key,
  product_id bigint not null
    references public.products(id)
    on delete cascade,
  color_id bigint,
  size_id bigint,
  price numeric not null,
  stock_quantity integer not null default 0,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint product_variants_price_nonnegative
    check (price >= 0),
  constraint product_variants_stock_quantity_nonnegative
    check (stock_quantity >= 0),
  constraint product_variants_color_product_fk
    foreign key (color_id, product_id)
    references public.product_colors(id, product_id)
    on update restrict
    on delete restrict,
  constraint product_variants_size_product_fk
    foreign key (size_id, product_id)
    references public.product_sizes(id, product_id)
    on update restrict
    on delete restrict
);


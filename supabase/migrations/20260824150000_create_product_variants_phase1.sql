create or replace function public.ensure_product_variant_parent_model()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_inventory_model text;
begin
  select product.inventory_model
    into v_inventory_model
  from public.products product
  where product.id = new.product_id
  for update;

  if not found then
    raise exception 'Product not found.' using errcode = 'P0002';
  end if;

  if v_inventory_model <> 'variants' then
    raise exception 'Product variants can only belong to variant-mode products.' using errcode = '23514';
  end if;

  return new;
end;
$$;

drop trigger if exists ensure_product_variant_parent_model on public.product_variants;

create trigger ensure_product_variant_parent_model
  before insert or update of product_id on public.product_variants
  for each row
  execute function public.ensure_product_variant_parent_model();

create or replace function public.prevent_variant_product_legacy_downgrade()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if old.inventory_model = 'variants'
    and new.inventory_model = 'legacy'
    and exists (
      select 1
      from public.product_variants
      where product_id = old.id
      limit 1
    )
  then
    raise exception 'Variant products with variants cannot be switched back to legacy.' using errcode = '23514';
  end if;

  return new;
end;
$$;

drop trigger if exists prevent_variant_product_legacy_downgrade on public.products;

create trigger prevent_variant_product_legacy_downgrade
  before update of inventory_model on public.products
  for each row
  execute function public.prevent_variant_product_legacy_downgrade();

create or replace function public.sync_product_variant_parent_price(
  p_product_id bigint
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_min_price numeric;
begin
  perform 1
  from public.products
  where id = p_product_id
  for update;

  if not found then
    return;
  end if;

  select min(price)
    into v_min_price
  from public.product_variants
  where product_id = p_product_id
    and is_active = true;

  if v_min_price is not null then
    update public.products
    set price = v_min_price
    where id = p_product_id
      and inventory_model = 'variants'
      and price is distinct from v_min_price;
  end if;
end;
$$;

create or replace function public.sync_product_variant_parent_price_trigger()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if tg_op = 'DELETE' then
    perform public.sync_product_variant_parent_price(old.product_id);
    return old;
  end if;

  if tg_op = 'UPDATE' and old.product_id is distinct from new.product_id then
    perform public.sync_product_variant_parent_price(old.product_id);
  end if;

  perform public.sync_product_variant_parent_price(new.product_id);
  return new;
end;
$$;

drop trigger if exists sync_product_variant_parent_price on public.product_variants;

create trigger sync_product_variant_parent_price
  after insert or update of product_id, price, is_active or delete on public.product_variants
  for each row
  execute function public.sync_product_variant_parent_price_trigger();

